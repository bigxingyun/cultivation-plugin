const tally = (l, f) => l.reduce((a, t) => ((a[f(t)] = (a[f(t)] || 0) + 1), a), {})
let ok = true

// ── 自检 + 排序 + 编序号 ───────────────────────────────────────────────
for (const r of REALMS) {
  r.list = r.rows.map(([id, name, tier, purpose, req, intro, success, fail]) => ({ id, name, tier, purpose, req, intro, success, fail }))
  // 同一 (档位,目的) 内保持表中出现顺序
  r.list.sort((a, b) => TIER_ORDER[a.tier] - TIER_ORDER[b.tier] || PURPOSE_ORDER[a.purpose] - PURPOSE_ORDER[b.purpose])
  const c = {}
  for (const t of r.list) {
    const key = `${t.tier}-${t.purpose}`
    c[key] = (c[key] || 0) + 1
    t.missionId = `m${r.rid}-${t.tier === '地' ? 4 : t.tier === '天' ? 5 : t.tier === '仙' ? 6 : 7}-${t.purpose}-${String(c[key]).padStart(2, '0')}`
  }
  const gotTier = tally(r.list, (t) => t.tier)
  const gotPurpose = tally(r.list, (t) => t.purpose)
  const pass = r.list.length === 21
    && JSON.stringify(gotTier) === JSON.stringify(r.tier)
    && JSON.stringify(gotPurpose) === JSON.stringify(r.purpose)
  if (!pass) ok = false
  console.log(`=== ${r.name} ${r.list.length}/21 ${pass ? 'OK' : 'MISMATCH'} ===`)
  console.log(`  档位 ${JSON.stringify(gotTier)}  期望 ${JSON.stringify(r.tier)}`)
  console.log(`  目的 ${JSON.stringify(gotPurpose)}  期望 ${JSON.stringify(r.purpose)}`)
}

const allNames = REALMS.flatMap((r) => r.list.map((t) => t.name))
const dup = [...new Set(allNames.filter((n, i) => allNames.indexOf(n) !== i))]
if (dup.length) { ok = false; console.log('内部重名：' + dup.join('、')) }
const EXISTING = '后山采药,驱赶野猪,清扫藏经阁,挑水三十担,修补篱笆,守夜,抄录残卷,涧边取水,追踪野狼,药田除虫,押送药箱,后山巡查,抄录旧档,押送份例,涧底清淤,驱赶灵猿,校对册页,界碑重立'.split(',')
const clash = allNames.filter((n) => EXISTING.includes(n))
if (clash.length) { ok = false; console.log('与已定稿重名：' + clash.join('、')) }
const total = REALMS.reduce((a, r) => a + r.list.length, 0)
if (total !== 42) { ok = false; console.log(`总条数 ${total} ≠ 42`) }
if (!ok) { console.log('\n❌ 自检未通过，未写入'); process.exit(1) }

// ── 写出 ───────────────────────────────────────────────────────────────
const out = []
for (const r of REALMS) {
  out.push(`### ${r.name}（${r.range}，${r.list.length} 条）`, '')
  for (const t of r.list) {
    out.push(`#### ${t.missionId} ｜ ${t.name}　\`${t.tier}\` \`${t.purpose}\` \`req ${t.req}\`　【占位】`)
    out.push(`- **intro**：${t.intro}`)
    out.push(`- **success**：${t.success}`)
    out.push(`- **fail**：${t.fail}`)
    out.push('')
  }
}
fs.writeFileSync(OUT, out.join('\n').replace(/\n+$/, '\n'), 'utf8')
console.log(`\n✅ 已写入 ${total} 条`)
